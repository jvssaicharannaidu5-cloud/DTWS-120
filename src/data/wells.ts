import { Well } from '../types';

export function jitter(n: number, amp: number): number {
  return n + (Math.random() - 0.5) * amp;
}

export function clamp(n: number, a: number, b: number): number {
  return Math.max(a, Math.min(b, n));
}

export function fmt(n: number | undefined | null, d = 1): string {
  if (n === undefined || n === null || isNaN(n)) return '0.0';
  return Number(n).toFixed(d);
}

export function spark(seed: number, n = 18): number[] {
  const a: number[] = [];
  let v = 40 + (seed % 30);
  for (let i = 0; i < n; i++) {
    v = clamp(v + Math.sin(i / 2 + seed) * 4 + (Math.random() - 0.5) * 6, 8, 92);
    a.push(Math.round(v * 10) / 10);
  }
  return a;
}

